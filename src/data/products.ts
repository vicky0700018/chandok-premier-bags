const slugify = (s: string) => s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/(^-|-$)/g, "");

export const products: Product[] = seeds.map((p) => ({
  ...p,
  slug: slugify(p.name),
  categoryName: catNames[p.category] ?? p.category,
  gallery: [p.image, ...p.gallery],
}));

export const discountOf = (p: { price: number; mrp: number }) =>
  Math.max(0, Math.round(((p.mrp - p.price) / p.mrp) * 100));

export const findProduct = (id: string) => products.find((p) => p.id === id || p.slug === id);
